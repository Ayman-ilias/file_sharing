// Copies the approved design into the app, so the CSS and icons can't drift from docs/design.
// Run: node scripts/extract-design.mjs   (re-run whenever docs/design/*.html changes)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const design = (f) => readFileSync(resolve(here, '../../docs/design', f), 'utf8')
const out = (f) => resolve(here, '..', f)

const styleOf = (html) => html.slice(html.indexOf('<style>') + 7, html.indexOf('</style>'))
const header = (src) => `/* GENERATED by scripts/extract-design.mjs from docs/design/${src} — do not edit by hand. */\n`

// 1) app.css = the mockup's whole <style> block, verbatim
const mockup = design('mockup.html')
writeFileSync(out('src/styles/app.css'), header('mockup.html') + styleOf(mockup).trim() + '\n')

// 2) states.css = only the component CSS that states.html adds, minus its gallery frame
const statesStyle = styleOf(design('states.html'))
const extra = statesStyle.slice(statesStyle.indexOf('/* ---------- states gallery'))
const galleryOnly = /^\s*(\.gal\b|\.gsec\b|\.ggrid\b|\.fr > \.cap|@media \(max-width: 860px\) \{ \.ggrid)/
const kept = extra.split('\n').filter((line) => !galleryOnly.test(line)).join('\n')
writeFileSync(out('src/styles/states.css'), header('states.html') + kept.trim() + '\n')

// 3) the SVG icon sprite (all <symbol>s from both files, once each) goes into index.html
const symbols = new Map()
for (const html of [mockup, design('states.html')]) {
  for (const m of html.matchAll(/<symbol id="(i-[a-z0-9]+)"[\s\S]*?<\/symbol>/g)) {
    if (!symbols.has(m[1])) symbols.set(m[1], m[0].trim())
  }
}
const sprite = `<svg width="0" height="0" style="position:absolute" aria-hidden="true">\n  ${[...symbols.values()].join('\n  ')}\n</svg>`
const indexPath = out('index.html')
const index = readFileSync(indexPath, 'utf8')
const start = '<!-- design-icons:start -->'
const end = '<!-- design-icons:end -->'
const block = `${start}\n    ${sprite}\n    ${end}`
const next = index.includes(start)
  ? index.replace(new RegExp(`${start}[\\s\\S]*?${end}`), block)
  : index.replace('<body>', `<body>\n    ${block}`)
writeFileSync(indexPath, next)
console.log(`app.css, states.css written; ${symbols.size} icons in index.html`)
